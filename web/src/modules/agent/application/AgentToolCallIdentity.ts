import type { ModelToolCall } from '@/capabilities/ai-runtime/public';

export function agentToolArgumentsHash(call: Pick<ModelToolCall, 'name' | 'arguments'>): string {
  const serialized = stableStringify({
    name: call.name,
    arguments: call.arguments
  });
  let first = 0x811c9dc5;
  let second = 0x9e3779b9;
  for (let index = 0; index < serialized.length; index += 1) {
    const code = serialized.charCodeAt(index);
    first = Math.imul(first ^ code, 0x01000193);
    second = Math.imul(second ^ code, 0x85ebca6b);
  }
  return `${(first >>> 0).toString(16).padStart(8, '0')}${(second >>> 0).toString(16).padStart(8, '0')}`;
}

export function cloneAgentToolCall(call: ModelToolCall): ModelToolCall {
  return {
    ...call,
    arguments: JSON.parse(JSON.stringify(call.arguments))
  };
}

function stableStringify(value: unknown): string {
  if (Array.isArray(value)) return `[${value.map(stableStringify).join(',')}]`;
  if (!value || typeof value !== 'object') return JSON.stringify(value) ?? 'null';
  return `{${Object.keys(value as Record<string, unknown>)
    .sort()
    .map((key) => `${JSON.stringify(key)}:${stableStringify((value as Record<string, unknown>)[key])}`)
    .join(',')}}`;
}
