export function practiceLectureResponseSchema(schema: JsonObject): JsonObject {
  const cloned = JSON.parse(JSON.stringify(schema)) as Record<string, unknown>;
  const properties = schemaRecord(cloned.properties, '$.properties');
  cloned.required = ['lecture'];
  delete properties.materialGroups;
  delete properties.questions;
  return cloned as JsonObject;
}

function schemaRecord(value: unknown, path: string): Record<string, unknown> {
  if (!value || typeof value !== 'object' || Array.isArray(value)) {
    throw new Error(`Structured generation schema is invalid at ${path}`);
  }
  return value as Record<string, unknown>;
}

function capabilityStructuralContract(capabilityCode: string): string {
  if (capabilityCode.startsWith('aptitude.data_analysis.')) {
    return [
      '本次是资料分析题。使用一个完整 materialGroups 公共资料承载数据表或统计材料，至少两道小题引用同一个 materialGroupId。',
      '公共资料中的表格使用标准 GFM Markdown，表头、分隔行和数据行必须完整；每道小题的 material 必须为 null。',
      '题干只保留当前小题的设问，选项只保留当前小题的候选答案，不要把资料表重复写入各题。'
    ].join('\n');
  }
  if (capabilityCode.startsWith('aptitude.judgment.graphical.')) {
    return [
      '本次是图形推理题。每道题必须提供一个完整、可独立渲染的 SVG visual，并包含 viewBox。',
      '图形顺序必须与规律顺序一致，使用 preserveAspectRatio 或等价的等比布局，不得拉伸、裁断或依赖横向滚动。',
      '若选项是图形，分别放入 option.visual；不要用文字、代码片段或拆散的多个 SVG 代替图形选项。'
    ].join('\n');
  }
  return '';
}

function isComplexVisualStructure(capabilityCode: string): boolean {
  return capabilityCode.startsWith('aptitude.data_analysis.')
    || capabilityCode.startsWith('aptitude.judgment.graphical.');
}
