/**
 * The first provider turn publishes one coherent teaching unit: lecture plus
 * answerable questions. A minimal knowledge-point block is published with each
 * answer; detailed explanations are generated by the durable enrichment workflow.
 */
export function practiceCoreResponseSchema(
  schema: JsonObject,
  exactQuestionCount?: number
): JsonObject {
  const cloned = JSON.parse(JSON.stringify(schema)) as Record<string, unknown>;
  const properties = schemaRecord(cloned.properties, '$.properties');
  const required = Array.isArray(cloned.required)
    ? cloned.required.filter((item): item is string => typeof item === 'string')
    : [];
  cloned.required = [...new Set([...required, 'lecture', 'questions'])];
  const questions = schemaRecord(properties.questions, '$.properties.questions');
  if (exactQuestionCount !== undefined) {
    const count = Math.max(1, Math.floor(exactQuestionCount));
    questions.minItems = count;
    questions.maxItems = count;
  }
  const question = schemaRecord(questions.items, '$.properties.questions.items');
  const questionProperties = schemaRecord(
    question.properties,
    '$.properties.questions.items.properties'
  );
  const questionRequired = Array.isArray(question.required)
    ? question.required.filter((item): item is string => typeof item === 'string')
    : [];
  question.required = [...new Set([
    ...questionRequired,
    'materialGroupId',
    'material',
    'explanation'
  ])];
  questionProperties.explanation = {
    type: 'object',
    additionalProperties: false,
    required: ['knowledgePoint'],
    properties: {
      knowledgePoint: { type: 'string', minLength: 2 }
    }
  };
  return cloned as JsonObject;
}

export function practiceQuestionShardSystem(
  system: string,
  capabilityCode = ''
): string {
  const structuralContract = capabilityStructuralContract(capabilityCode);
  return [
    system,
    '# 配套题目分片',
    '本轮只生成 questions 和必要的 materialGroups，不重新生成 lecture。',
    '用户消息中的 teachingContract 是本套题唯一的教学契约，必须围绕其中的知识、方法、边界和难度生成本分片题目。',
    '不得改变教学目标，不得输出与 teachingContract 无关的泛题。',
    '每道题必须提供可立即作答的材料、题干、选项、正确答案和 knowledgePoint；详细解析由后续无感补全。',
    'batch.existingQuestionSummaries 是其他分片已占用的设问方向，只用于去重，不得照抄。',
    ...(structuralContract ? ['# 当前题型必要结构', structuralContract] : [])
  ].join('\n\n');
}

export function practiceQuestionShardResponseSchema(
  schema: JsonObject,
  exactQuestionCount: number
): JsonObject {
  const cloned = practiceCoreResponseSchema(schema, exactQuestionCount) as Record<string, unknown>;
  const properties = schemaRecord(cloned.properties, '$.properties');
  delete properties.lecture;
  cloned.required = (Array.isArray(cloned.required) ? cloned.required : [])
    .filter((item) => item !== 'lecture');
  return cloned as JsonObject;
}

